BOOKKEEPING = {"SELECT count(*) FROM raw", "DESCRIBE raw"}  # the engine counts and reads the header; not data code


def test_the_engine_runs_exactly_the_generated_statements(db_session, glossary, tmp_path):
    w = make_world(db_session, tmp_path)
    run_to(w, "go_live")
    code = code_for_feed(db_session, w.feed_id)
    test_load = next(x for x in LoadRepository(db_session).list_for_feed(w.feed_id) if x.purpose == "go_live_test")
    plan = engine_plan_for(db_session, w.feed_id, test_load)
    assert isinstance(plan, LoadPlan)

    outcome = execute_load(plan, blob_store=w.ctx.blob_store, rule_timeout_seconds=w.settings.rule_timeout_seconds)

    assert outcome.failed is None and outcome.executed_sql
    ran = [s for s in outcome.executed_sql if s not in BOOKKEEPING]
    assert set(ran) <= set(code.statements), [s for s in ran if s not in code.statements]  # nothing runs that is not shown
    always = [s for s in code.statements if s in set(code.always_run)]
    assert all(s in ran for s in always)  # what always runs was run
    for rule in plan.rules:  # a rule's file is its SQL, byte for byte
        assert code.files[f"rules/{rule.rule_key}.sql"].strip().rstrip(";") == rule.sql.strip().rstrip(";")
        assert rule.sql in ran


def test_the_files_are_plain_text_a_person_can_read_and_the_hash_is_stable(db_session, glossary, tmp_path):
    w = make_world(db_session, tmp_path)
    run_to(w, "go_live")
    before = db_session.scalar(select(func.count()).select_from(ProposalLogEntry))
    first, again = code_for_feed(db_session, w.feed_id), code_for_feed(db_session, w.feed_id)
    assert db_session.scalar(select(func.count()).select_from(ProposalLogEntry)) == before  # no model
    assert first.files == again.files and first.sha256 == again.sha256 == sha256_of(first.files)
    assert {"staging_ddl.sql", "load.sql", "curated.sql", "README.md"} <= set(first.files)
    assert first.files["staging_ddl.sql"].startswith("-- Generated by Amaze")
    readme = first.files["README.md"]
    assert "Purpose" in readme and "Transformations" in readme and "Rules" in readme and "Columns" in readme
    for rule in plan_rules(first):
        assert rule in readme


def plan_rules(code) -> list[str]:
    return [p.removeprefix("rules/").removesuffix(".sql") for p in code.files if p.startswith("rules/")]


def test_a_changed_configuration_changes_the_hash_and_the_diff_names_the_file():
    old = {"curated.sql": "SELECT 1;\n", "README.md": "# a\n"}
    new = {"curated.sql": "SELECT 2;\n", "README.md": "# a\n", "rules/r.sql": "SELECT _row FROM curated;\n"}
    assert sha256_of(old) != sha256_of(new)
    diff = diff_versions(old, new)
    assert [d.path for d in diff] == ["curated.sql", "rules/r.sql"] and [d.change for d in diff] == ["changed", "added"]
    assert "-SELECT 1;" in diff[0].diff and "+SELECT 2;" in diff[0].diff
    assert diff_versions(old, old) == []


def test_the_go_live_approval_stores_code_version_one_and_pins_it(db_session, glossary, tmp_path):
    from core.steps.onboarding import approve_and_next
    from tests.test_onboarding import OPERATOR, approve, current

    w = make_world(db_session, tmp_path)
    run_to(w, "go_live")
    assert CodeVersionRepository(db_session).list_for_feed(w.feed_id) == []  # nothing is stored before the approval
    approve(w)
    [v1] = CodeVersionRepository(db_session).list_for_feed(w.feed_id)
    live = GoLiveRepository(db_session).latest(w.feed_id)
    assert (v1.version, v1.approved_by, live.code_version_id) == (1, "dev-operator", v1.id)
    assert v1.sha256 == sha256_of(v1.files) and v1.test_load_id == live.test_load_id
    assert v1.test_load_result["status"] == "loaded" and v1.test_load_result["rows"] > 0
    assert set(v1.mapping_ids) == set(live.mapping_ids) and set(v1.rule_ids) == set(live.rule_ids)
    assert v1.files == code_for_feed(db_session, w.feed_id).files  # the code stored is the code the engine now runs
    assert current(w).current_step == "first_load" and approve_and_next and OPERATOR


