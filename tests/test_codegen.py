def test_code_versions_are_append_only(stored, db_session):
    for sql in ("UPDATE code_versions SET approved_by = 'x'", "DELETE FROM code_versions"):
        with pytest.raises(DBAPIError, match="append-only|restrict"):
            with db_session.begin_nested():
                db_session.execute(text(sql))


def test_a_go_live_must_pin_a_code_version_of_its_own_feed_approved_by_the_same_owner(stored, db_session):
    live = GoLiveRepository(db_session).latest(stored.feed_id)
    insert = ("INSERT INTO feed_go_lives (feed_id, version, proposal_id, approved_by, mapping_ids, rule_ids, "
              "transformation_ids, test_load_id, hypercare_until, code_version_id) "
              "SELECT feed_id, version + 1, proposal_id, approved_by, mapping_ids, rule_ids, transformation_ids, "
              "test_load_id, hypercare_until, {pin} FROM feed_go_lives WHERE id = :id")
    for pin, why in (("NULL", "code version"),):
        with pytest.raises(DBAPIError, match=why):
            with db_session.begin_nested():
                db_session.execute(text(insert.format(pin=pin)), {"id": live.id})


def test_code_version_numbers_run_one_two_three_per_feed(stored, db_session):
    v1 = CodeVersionRepository(db_session).latest(stored.feed_id)
    row = ("INSERT INTO code_versions (feed_id, version, sha256, files, mapping_ids, rule_ids, transformation_ids, "
           "test_load_id, test_load_result, approved_by) SELECT feed_id, :v, sha256, files, mapping_ids, rule_ids, "
           "transformation_ids, test_load_id, test_load_result, approved_by FROM code_versions WHERE id = :id")
    with pytest.raises(DBAPIError, match="next one"):
        with db_session.begin_nested():
            db_session.execute(text(row), {"v": 3, "id": v1.id})
    with pytest.raises(DBAPIError, match="next one|duplicate|unique"):
        with db_session.begin_nested():
            db_session.execute(text(row), {"v": 1, "id": v1.id})


