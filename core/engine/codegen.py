"""Generated code for a feed (phase 7.12, T3): deterministic text from the approved configuration, no model (rule 2).

The files are built from the same functions the engine runs: raw_load_sql(), curated_sql(), uncast_sql(),
duplicate_probe_sql(), keep_last_sql(), curated_rows_sql() and each rule's own SQL. So code shown = code run, and a test
proves it: the statements execute_load() ran are a subset of `GeneratedCode.statements`, and `always_run` all ran.

Files:  staging_ddl.sql   the shape of the raw table (every column text), for a reader or a database that stages the file
        load.sql          the statement that reads the file into `raw`
        curated.sql       the cast and the curated rows, the unreadable-value check, the duplicate-key policy
        rules/<key>.sql   each approved rule, exactly as stored
        README.md         purpose, columns, transformations, rules (documentation)
Generated code is never hand-edited: a person changes the configuration, and the next code version is generated.
"""

from __future__ import annotations

import difflib
import hashlib
from typing import Literal

from pydantic import BaseModel, ConfigDict

from core.engine.curate import (
    Found,
    curated_rows_sql,
    curated_sql,
    duplicate_probe_sql,
    keep_last_sql,
    key_columns_found,
    match_header,
    quoted,
    uncast_sql,
)
from core.engine.run import Configuration
from core.engine.sandbox import raw_load_sql
from core.engine.transform import label_of

BANNER = ("-- Generated by Amaze from the approved configuration. Do not edit this file: change the configuration\n"
          "-- and a new code version is generated. The engine runs exactly these statements.")


class GeneratedCode(BaseModel):
    model_config = ConfigDict(frozen=True)

    files: dict[str, str]
    statements: list[str]  # every statement the engine may run for this configuration, as it runs it
    always_run: list[str]  # the ones it runs on every load
    sha256: str


def sha256_of(files: dict[str, str]) -> str:
    """The hash of the files: sorted by path, each as path, a unit separator and the content, joined by a record
    separator. The database computes the same text and refuses a version whose hash differs (migration 0030)."""
    text = "\x1e".join(f"{path}\x1f{files[path]}" for path in sorted(files))
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _block(banner: bool, parts: list[tuple[str, str]]) -> str:
    out = [BANNER] if banner else []
    for comment, sql in parts:
        out.append(f"\n-- {comment}\n{sql};")
    return "\n".join(out) + "\n"


def generate_code(*, feed_code: str, feed_name: str, configuration: Configuration, header: list[str]) -> GeneratedCode:
    """`header`: the file's column names as the latest profile saw them (the engine matches them to the mapped names)."""
    steps_of = {t.source_field.lower(): tuple(t.steps) for t in configuration.transformations}
    found, missing, unmapped = match_header(configuration.columns, header, steps_of)
    for column in configuration.columns:  # a mapped column the profile lacks: shown under its mapped name
        if column.source_field in missing:
            found.append(Found(column.source_field, column.source_field, column.element_key, column.data_type,
                               tuple(steps_of.get(column.source_field.lower(), ()))))
    statements: list[str] = []
    always: list[str] = []

    def add(sql: str, *, always_runs: bool = True) -> str:
        statements.append(sql)
        if always_runs:
            always.append(sql)
        return sql

    load = add(raw_load_sql())
    ddl = "CREATE TABLE raw (\n  _row BIGINT,\n" + ",\n".join(f"  {quoted(h)} VARCHAR" for h in header) + "\n)"
    curated_parts: list[tuple[str, str]] = []
    if found:
        curated_parts.append(("Cast each mapped column to its element's type; an empty cell is already NULL.",
                              add(curated_sql(found))))
        for f in found:
            curated_parts.append((f"Values of {f.source_field} that are not empty and did not cast: the file is held.",
                                  add(uncast_sql(f))))
        policy = configuration.key_policy
        keys, _ = key_columns_found(found, policy.key_columns) if policy else ([], [])
        if policy and keys:
            curated_parts.append((f"Duplicate-key policy '{policy.policy}': the rows whose key repeats.",
                                  add(duplicate_probe_sql(keys))))
            if policy.policy == "keep_last":
                curated_parts.append(("keep_last: only the last row of each repeated key stays.",
                                      add(keep_last_sql(keys), always_runs=False)))
        curated_parts.append(("The curated rows that become standard records.", add(curated_rows_sql(found))))
    files: dict[str, str] = {
        "staging_ddl.sql": _block(True, [("The shape of the raw table: every column is text; `_row` is the data row "
                                          "number in file order. load.sql creates it.", ddl)]),
        "load.sql": _block(True, [("Read the file into raw.", load)]),
        "curated.sql": _block(True, curated_parts) if curated_parts else BANNER + "\n-- No column is mapped yet.\n",
    }
    for rule in configuration.rules:  # exactly the stored SQL: the engine runs this text
        add(rule.sql)
        files[f"rules/{rule.rule_key}.sql"] = rule.sql.rstrip() + "\n"
    files["README.md"] = _readme(feed_code, feed_name, found, missing, unmapped, configuration)
    return GeneratedCode(files=files, statements=statements, always_run=always, sha256=sha256_of(files))


def _readme(feed_code: str, feed_name: str, found: list[Found], missing: list[str], unmapped: list[str],
            configuration: Configuration) -> str:
    lines = [f"# {feed_name} ({feed_code})", "", "Generated by Amaze from the approved configuration. Do not edit.", "",
             "## Purpose", "",
             f"Each delivery of {feed_name} is read as text, its mapped columns are cast to their glossary types, "
             "the approved rules flag rows that break them, and the result becomes the feed's standard records.", "",
             "## Columns", "", "| File column | Element | Type | Cleaned by |", "|---|---|---|---|"]
    for f in found:
        steps = ", ".join(s.op for s in f.steps) or "nothing"
        label = label_of(f.steps)
        lines.append(f"| {f.header} | {f.element_key}{f' (shown as {label})' if label else ''} | {f.data_type} | {steps} |")
    if missing:
        lines += ["", f"Mapped but not seen in the last profile: {', '.join(missing)}."]
    if unmapped:
        lines += ["", f"In the file, not mapped (not loaded): {', '.join(unmapped)}."]
    lines += ["", "## Transformations", ""]
    transformed = [f for f in found if f.steps]
    lines += ([f"- {f.header}: {', '.join(s.op for s in f.steps)}" for f in transformed] or ["None."])
    lines += ["", "## Rules", ""]
    lines += ([f"- {r.rule_key}: `rules/{r.rule_key}.sql`" for r in configuration.rules] or ["None."])
    policy = configuration.key_policy
    lines += ["", "## Duplicate keys", "",
              f"{policy.policy} on {', '.join(policy.key_columns)}." if policy else "No key policy."]
    return "\n".join(lines) + "\n"


class FileDiff(BaseModel):
    model_config = ConfigDict(frozen=True)

    path: str
    change: Literal["added", "removed", "changed"]
    diff: str  # unified diff, empty for a whole new or removed file's lines shown as + or -


def diff_versions(old: dict[str, str], new: dict[str, str]) -> list[FileDiff]:
    """Which files differ between two versions, with a unified diff of each; none when they are the same."""
    found: list[FileDiff] = []
    for path in sorted(set(old) | set(new)):
        before, after = old.get(path), new.get(path)
        if before == after:
            continue
        change = "added" if before is None else "removed" if after is None else "changed"
        text = "".join(difflib.unified_diff((before or "").splitlines(keepends=True), (after or "").splitlines(keepends=True),
                                            fromfile=f"v-old/{path}", tofile=f"v-new/{path}"))
        found.append(FileDiff(path=path, change=change, diff=text))
    return found
